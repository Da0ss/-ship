# --- JSON schemas (OpenAPI subset accepted by Gemini response_schema) -------------------------

def _str(**kw: Any) -> dict[str, Any]:
    return {"type": "string", **kw}


def _status_obj(keys: list[str]) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": {k: _str(enum=["pass", "fail", "n/a"]) for k in keys},
        "required": keys,
    }


VIOLATION_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "defect": _str(enum=list(DEFECT_TYPES)),
        "criterion": _str(),
        "severity": _str(enum=list(SEVERITIES)),
        "quote": _str(),
        "quote2": _str(nullable=True),
        "explanation": _str(),
        "fix": _str(),
    },
    "required": ["defect", "criterion", "severity", "quote", "explanation", "fix"],
}

EXTRACT_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "requirements": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "doc_id": _str(nullable=True),
                    "section": _str(),
                    "kind": _str(enum=KINDS),
                    "quote": _str(),
                    "line_start": {"type": "integer"},
                    "line_end": {"type": "integer"},
                    "summary": _str(),
                },
                "required": ["section", "kind", "quote", "line_start", "line_end", "summary"],
            },
        }
    },
    "required": ["requirements"],
}

CHECK_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "checks": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "rid": _str(),
                    "characteristics": _status_obj(list(REQ_CHARACTERISTICS)),
                    "violations": {"type": "array", "items": VIOLATION_SCHEMA},
                },
                "required": ["rid", "characteristics", "violations"],
            },
        }
    },
    "required": ["checks"],
}

SET_VIOLATION_SCHEMA: dict[str, Any] = {
    **VIOLATION_SCHEMA,
    "properties": {**VIOLATION_SCHEMA["properties"], "req_ids": {"type": "array", "items": _str()}},
    "required": VIOLATION_SCHEMA["required"] + ["req_ids"],
}

SET_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "characteristics": _status_obj(list(SET_CHARACTERISTICS)),
        "violations": {"type": "array", "items": SET_VIOLATION_SCHEMA},
    },
    "required": ["characteristics", "violations"],
}

VERDICT_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {"summary": _str(), "fix_first": {"type": "array", "items": _str()}},
    "required": ["summary", "fix_first"],
}


def describe(chars: dict[str, str]) -> str:
    return "\n".join(f"- {k}: {v}" for k, v in chars.items())


def dumps(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=1)
